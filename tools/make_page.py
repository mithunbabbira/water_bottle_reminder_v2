#!/usr/bin/env python3
"""Rebuild bottle/WebPageGz.h from bottle/WebPage.h. Run after editing the page."""

import gzip
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
source = (root / "bottle" / "WebPage.h").read_text(encoding="utf-8")
match = re.search(r'R"html\((.*)\)html"', source, re.S)
if match is None:
    raise SystemExit("BOTTLE_PAGE raw string not found in WebPage.h")

html = match.group(1).encode("utf-8")
packed = gzip.compress(html, compresslevel=9, mtime=0)

rows = []
for i in range(0, len(packed), 20):
    rows.append("  " + ",".join(f"0x{b:02x}" for b in packed[i : i + 20]) + ",")

out = (
    "#pragma once\n\n"
    "// Generated by tools/make_page.py from WebPage.h. Do not edit by hand.\n\n"
    "#include <Arduino.h>\n\n"
    f"static const size_t BOTTLE_PAGE_GZ_LEN = {len(packed)};\n"
    "static const uint8_t BOTTLE_PAGE_GZ[] PROGMEM = {\n" + "\n".join(rows) + "\n};\n"
)
(root / "bottle" / "WebPageGz.h").write_text(out, encoding="utf-8")
print(f"page {len(html)} bytes, gzip {len(packed)} bytes")
